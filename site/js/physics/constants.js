// Физические константы и параметры по умолчанию. Всё в СИ.

export const G0 = 9.80665; // стандартное ускорение свободного падения, м/с²

export const rpmToOmega = (rpm) => (rpm * 2 * Math.PI) / 60;
export const omegaToRpm = (w) => (w * 60) / (2 * Math.PI);

// Оценочные параметры корабля класса Starship. Публичных точных данных нет,
// поэтому все величины вынесены в настройки и подписаны на сайте как оценки.
export const STARSHIP = {
  M: 150e3, // масса корабля (сухая ~100–130 т + груз/остаток топлива), кг
  length: 50, // длина, м
  diameter: 9, // диаметр, м
  cmFromNose: 30, // расстояние от носа (точки крепления троса) до центра масс, м
  deckFromNose: 10, // расстояние от носа до пола жилой палубы, м
  gyration: 14, // радиус инерции относительно центра масс (поперёк оси), м: I = M·k²
};

// Низкая околоземная орбита ~400 км: период ≈ 92,6 мин.
export const LEO_MEAN_MOTION = (2 * Math.PI) / (92.6 * 60); // рад/с
